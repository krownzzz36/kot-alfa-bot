#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Юнит-тесты парсеров СМАШЕРА на реальных строках @holop.
Запуск:  python test_smash_parsers.py

Зачем: именно в парсерах были все недавние баги (двойной счёт «Сердца» в регене,
«видит 78 считает 75», штраф репутации ловился на подстроку). Эти тесты — регресс-
защита: правишь регэксп/строку игры → сразу видно, не сломался ли разбор.
"""
from holop_smash import (
    parse_regen_bonus, parse_my_low_hp, parse_result_my_hp,
    parse_shield_seconds, parse_mine_seconds, parse_rep, parse_rep_penalty,
    parse_duration, parse_amount,
)

# ── РЕАЛЬНЫЙ экран «Территория» Владимира (снят вживую 24.07.2026) ──
TERRITORY = (
    "🏰 ТЕРРИТОРИЯ «❤️ Vladimir🔖»\n"
    "❤️ Здоровье: 94/100\n"
    "📈 Репутация: 19144 (+34%)\n"
    "   └ ❤️‍🩹 Регенерация: +50%\n"
    "🎨 ❤️ Сердце: +50%❤️\n"
    "👑 Бонусы княжества: ⚔️ +35% атака, 🛡️ +35% защита, ❤️🩹 +6% реген\n"
    "🦸 Герои: ❤️ +21% реген, 💰 +17% лут"
)

_fails = []
def check(name, got, want):
    ok = got == want
    print(f"{'✅' if ok else '❌'} {name}: got={got!r} want={want!r}")
    if not ok:
        _fails.append(name)

# ── РЕГЕН (главный: «Сердце» = «Регенерация» — ОДИН бонус, показан дважды) ──
check("реген: сердце НЕ удваивается (+77, не +127)", parse_regen_bonus(TERRITORY), 77.0)
check("реген: только сердце показано дважды → 50", parse_regen_bonus(
    "❤️‍🩹 Регенерация: +50%\n🎨 ❤️ Сердце: +50%❤️"), 50.0)
check("реген: сердце + герои", parse_regen_bonus(
    "🎨 ❤️ Сердце: +50%❤️\n🦸 Герои: ❤️ +21% реген"), 71.0)
check("реген: нет бонусов → 0", parse_regen_bonus("🏰 ТЕРРИТОРИЯ\n❤️ Здоровье: 50/100"), 0.0)

# ── МОИ HP (знаменатель любой: амулет жизни → /120) ──
check("HP: Здоровье 94/100", parse_my_low_hp(TERRITORY), 94)
check("HP: Жизни 54/120 (амулет)", parse_my_low_hp("Жизни: 54/120"), 54)
check("HP: нет → None", parse_my_low_hp("нет здоровья тут"), None)
check("HP из итога боя (после ━)", parse_result_my_hp(
    "ТРИУМФ! Урон: 22 ━━━ 🏙️ ❤️ Vladimir: ❤️ 36/100 🏙️ Враг: ❤️ 75/100"), 36)

# ── ЩИТ / БОЧКА / ДЛИТЕЛЬНОСТЬ ──
check("щит: остаток из профиля", parse_shield_seconds(
    "🛡️ Статус • Полевой щит — 10ч 8мин"), 10 * 3600 + 8 * 60)
check("бочка: осталось до взрыва", parse_mine_seconds("⏰ Осталось: 9м 44с"), 9 * 60 + 44)
check("длительность: 23ч 59мин", parse_duration("23ч 59мин"), 23 * 3600 + 59 * 60)

# ── РЕПУТАЦИЯ (штраф — ТОЛЬКО минус у самой репутации; победа с «Потери» ≠ штраф) ──
check("реп заработана: +2.0", parse_rep("📈 +2.0 репутации"), 2.0)
check("штраф: -5 репутации → отрицательное", parse_rep_penalty("Списано -5 репутации") < 0, True)
check("НЕ штраф: победа с потерями", parse_rep_penalty(
    "👑 ТРИУМФ! ❤️ Потери в бою: 2 📈 +1 репутация") >= 0, True)
check("НЕ штраф: нет слова репутация", parse_rep_penalty("Урон 22, потери 2"), 0.0)

# ── СУММЫ ──
check("сумма: 3.6M", parse_amount("3.6M"), 3_600_000)
check("сумма: 214 300", parse_amount("214 300"), 214_300)

print()
if _fails:
    print(f"❌ ПРОВАЛЕНО: {len(_fails)} — {', '.join(_fails)}")
    raise SystemExit(1)
print("ВСЕ ТЕСТЫ ПАРСЕРОВ СМАШЕРА ПРОЙДЕНЫ ✅")
